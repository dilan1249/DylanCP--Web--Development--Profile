function cerrarMenu() {

  document.getElementById("nav").className = "";

  menuVisible = false;

}


/* ============================================================
   6. BARRAS DE HABILIDADES
   ============================================================ */

function animarHabilidades() {

  const barras =
    document.querySelectorAll(".progreso");


  const mostrar = barra => {

    const porcentaje =
      barra.getAttribute("data-percent") || "0";


    barra.style.width =
      porcentaje + "%";


    const etiqueta =
      barra.querySelector("span");


    if (etiqueta) {

      etiqueta.textContent =
        porcentaje + "%";

    }

  };


  /* Si el navegador no soporta
     IntersectionObserver */

  if (!("IntersectionObserver" in window)) {

    barras.forEach(mostrar);

    return;

  }


  /* Observador para detectar
     cuándo aparece la barra */

  const observador =
    new IntersectionObserver(

      (entradas, obs) => {

        entradas.forEach(entrada => {

          if (entrada.isIntersecting) {

            mostrar(entrada.target);

            obs.unobserve(
              entrada.target
            );

          }

        });

      },

      {
        threshold: 0.4
      }

    );


  barras.forEach(
    barra => observador.observe(barra)
  );

}


